# -*- coding: utf-8 -*-
"""Freeze the single-arm cube scene for Member B, with one monocular workspace camera.

This is the artifact behind 「固定单臂方块抓取仿真场景与物理参数」.  It does NOT
edit droid_cube_scene.xml -- that file is the team's frozen scene and is treated
as read-only here.  Instead it writes a thin wrapper that <include>s it and adds a
fixed camera, then compiles the result and dumps every physical parameter it can
read back out of the compiled model into a sibling .json, in the same shape as
the other scene .json files in simulation/v1/.

The hash guard exists because build_droid_object_scene.py's ensure_scene() will
happily REGENERATE simulation/v1/droid_cube_scene.xml from a different source
scene if the mtimes line up the wrong way.  `--verify` re-checks the recorded
hash and fails loudly if the frozen scene has moved under us.

    python build_droid_cube_perception_scene.py            # build xml + json
    python build_droid_cube_perception_scene.py --verify   # hash guard only
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import mujoco
import numpy as np

ROOT = Path(__file__).resolve().parent
SCENE_DIR = ROOT / "simulation" / "v1"
FROZEN = SCENE_DIR / "droid_cube_scene.xml"
WRAPPER = SCENE_DIR / "droid_cube_scene_perception.xml"
CONFIG = SCENE_DIR / "droid_cube_scene_perception.json"

CUBE_HALF = 0.0288          # from build_droid_object_scene.py, OBJECTS["cube"]
CUBE_MASS = 0.18
CUBE_SPAWN = [0.45, 0.0, 0.401]
TABLE_HALF_Z = 0.02
TABLE_POS_Z = 0.336
CAM_NAME = "workspace_camera"
CAM_DIST = 0.85             # metres above the workspace centre
CAM_ELEV_DEG = 90.0         # overhead view avoids robot-arm occlusion
CAM_FOVY = 55.0
IMG_W, IMG_H = 640, 480
PAD_TORSIONAL_FRICTION = 0.03

TEMPLATE = """<mujoco model="droid_cube_scene_perception">
  <!-- Frozen single-arm cube scene + one fixed monocular workspace camera.
       Generated by build_droid_cube_perception_scene.py from
       {base} (sha256 {sha}).
       That file is read-only here; nothing in it is regenerated or edited. -->
  <include file="{base}"/>
  <option noslip_iterations="10" noslip_tolerance="1e-6"/>
  <worldbody>
    <camera name="{name}" mode="fixed" pos="{pos}" quat="{quat}" fovy="{fovy}"/>
    <!-- Viewer-only reference for the original cube centre.  A site has no
         collision or mass, so it cannot influence perception, IK or physics. -->
    <site name="cube_spawn_reference" type="cylinder" pos="0.45 0 0.3575"
          size="0.014 0.0015" rgba="0.1 1 0.1 0.9"/>
  </worldbody>
  <!-- The imported pad meshes make one point contact on each opposing face.
       condim=4 adds the torsional resistance of a finite real pad patch; the
       grasp remains a pure contact/friction grasp and uses no weld. -->
  <contact>
    <pair geom1="droid_object_geom" geom2="openarm_right_right_finger_collision"
          condim="4" friction="1 1 {torsion} 0.0001 0.0001" solref="0.005 1"/>
    <pair geom1="droid_object_geom" geom2="openarm_right_left_finger_collision"
          condim="4" friction="1 1 {torsion} 0.0001 0.0001" solref="0.005 1"/>
    <pair geom1="droid_object_geom" geom2="openarm_left_right_finger_collision"
          condim="4" friction="1 1 {torsion} 0.0001 0.0001" solref="0.005 1"/>
    <pair geom1="droid_object_geom" geom2="openarm_left_left_finger_collision"
          condim="4" friction="1 1 {torsion} 0.0001 0.0001" solref="0.005 1"/>
  </contact>
</mujoco>
"""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def camera_pose(target):
    """Fixed camera on the -y side at CAM_ELEV, aimed at `target`.

    MuJoCo cameras look down their own -z, so mju_quatZ2Vec must be handed
    (camera - target), NOT (target - camera).  The two differ by a 180 degree
    turn and the wrong one renders a black frame with no error at all -- it was
    verified by rendering an image, not by reading the quaternion back.
    """
    pos = np.asarray(target, dtype=float) + np.array(
        [0.0, -CAM_DIST * np.cos(np.deg2rad(CAM_ELEV_DEG)),
         CAM_DIST * np.sin(np.deg2rad(CAM_ELEV_DEG))])
    d = pos - np.asarray(target, dtype=float)
    q = np.zeros(4)
    mujoco.mju_quatZ2Vec(q, d / np.linalg.norm(d))
    return pos, q


def world_aabb(model, data, geom_id):
    """Axis-aligned world bounds of a box geom."""
    c = data.geom_xpos[geom_id].copy()
    R = data.geom_xmat[geom_id].reshape(3, 3)
    s = model.geom_size[geom_id]
    corners = np.array([[sx, sy, sz] for sx in (-s[0], s[0])
                        for sy in (-s[1], s[1]) for sz in (-s[2], s[2])])
    pts = c + (R @ corners.T).T
    return pts.min(axis=0), pts.max(axis=0)


def build() -> int:
    if not FROZEN.is_file():
        print(f"frozen scene missing: {FROZEN}", file=sys.stderr)
        return 1
    src_sha = sha256(FROZEN)

    table_top = TABLE_POS_Z + TABLE_HALF_Z
    target = np.array([CUBE_SPAWN[0], CUBE_SPAWN[1], table_top + CUBE_HALF])
    pos, quat = camera_pose(target)
    WRAPPER.write_text(
        TEMPLATE.format(base=FROZEN.name, sha=src_sha, name=CAM_NAME, fovy=CAM_FOVY,
                        torsion=PAD_TORSIONAL_FRICTION,
                        pos=" ".join(f"{p:.6f}" for p in pos),
                        quat=" ".join(f"{q:.9f}" for q in quat)),
        encoding="utf-8", newline="\n")
    wrapper_sha = sha256(WRAPPER)

    model = mujoco.MjModel.from_xml_path(str(WRAPPER))
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    mujoco.mj_forward(model, data)
    # keyframe 0 drops the object at its spawn height; let it fall and settle so
    # "resting_pose" is the pose the grasp actually has to aim at
    while data.time < 2.0:
        mujoco.mj_step(model, data)

    gid = lambda n: mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, n)   # noqa: E731
    bid = lambda n: mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n)   # noqa: E731
    og, ob = gid("droid_object_geom"), bid("droid_object")

    lo, hi = world_aabb(model, data, og)
    resting_z = float(data.xpos[ob, 2])
    f = model.cam_fovy[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_CAMERA, CAM_NAME)]
    focal = 0.5 * IMG_H / np.tan(0.5 * np.deg2rad(f))

    # Look through the camera.  A camera aimed the wrong way renders a perfectly
    # black frame and raises nothing, so this is the only way to catch it.
    rend = mujoco.Renderer(model, IMG_H, IMG_W)
    rend.update_scene(data, camera=CAM_NAME)
    frame = rend.render().copy()
    rend.close()
    lit = int(np.count_nonzero(frame.any(axis=2)))
    lit_frac = lit / float(IMG_W * IMG_H)
    if lit_frac < 0.01:
        print(f"camera {CAM_NAME} renders an essentially black frame "
              f"({lit} lit pixels, {lit_frac*100:.2f}%). It is aimed away from the "
              f"scene. Check the sign of (camera - target) in camera_pose().",
              file=sys.stderr)
        return 1

    config = {
        "role": "Member B -- frozen single-arm grasp scene and physics parameters",
        "source_xml": str(FROZEN),
        "source_sha256": src_sha,
        "source_unmodified": True,
        "output_xml": str(WRAPPER),
        "output_sha256": wrapper_sha,
        "mujoco_version": mujoco.__version__,
        "compilation": "PASS",
        "frozen_source_rule": (
            "droid_cube_scene.xml is read-only. Never regenerate it -- "
            "build_droid_object_scene.py:ensure_scene() overwrites it from "
            "folding_scene_V25_4_TOWEL_SUPPORT_04.xml when the mtimes line up. "
            "Run this script with --verify to detect that."),
        "model": {
            "name": "droid_cube_scene_perception",
            "nq": int(model.nq), "nv": int(model.nv), "njnt": int(model.njnt),
            "nu": int(model.nu), "ncam": int(model.ncam), "ngeom": int(model.ngeom),
            "timestep_s": float(model.opt.timestep),
            "integrator": int(model.opt.integrator),
            "solver": int(model.opt.solver),
            "iterations": int(model.opt.iterations),
            "noslip_iterations": int(model.opt.noslip_iterations),
            "noslip_tolerance": float(model.opt.noslip_tolerance),
        },
        "table": {
            "geom": "folding_table",
            "center": [0.45, 0.0, TABLE_POS_Z],
            "half_size": [0.25, 0.35, TABLE_HALF_Z],
            "top_z": table_top,
            "friction": list(model.geom_friction[gid("folding_table")]),
        },
        "object": {
            "body": "droid_object",
            "body_id": int(ob),
            "geom": "droid_object_geom",
            "geom_id": int(og),
            "shape": "box",
            "half_size_m": list(model.geom_size[og].copy()),
            "edge_m": float(2 * CUBE_HALF),
            "mass_kg": float(model.body_mass[ob]),
            "weight_n": float(model.body_mass[ob] * 9.81),
            "diaginertia": list(model.body_inertia[ob].copy()),
            "rgba": list(model.geom_rgba[og].copy()),
            "friction": list(model.geom_friction[og].copy()),
            "condim": int(model.geom_condim[og]),
            "solref": list(model.geom_solref[og].copy()),
            "solimp": list(model.geom_solimp[og].copy()),
            "spawn_pose": CUBE_SPAWN,
            "resting_pose": [float(v) for v in data.xpos[ob]],
            "resting_aabb_lo": [float(v) for v in lo],
            "resting_aabb_hi": [float(v) for v in hi],
            "note": "rgba red is what the monocular perception mask keys on; "
                    "friction[0]=1.0 is the sliding coefficient the grasp relies on.",
        },
        "camera": {
            "name": CAM_NAME,
            "mode": "fixed",
            "role": "monocular workspace camera for cube localisation",
            "pos": [float(v) for v in pos],
            "quat": [float(v) for v in quat],
            "look_at": [float(v) for v in target],
            "distance_m": CAM_DIST,
            "elevation_deg": CAM_ELEV_DEG,
            "fovy_deg": CAM_FOVY,
            "resolution_wh": [IMG_W, IMG_H],
            "intrinsics_640x480": {
                "fx": float(focal), "fy": float(focal),
                "cx": IMG_W / 2.0, "cy": IMG_H / 2.0,
                "note": "square pixels assumed; validated by silhouette IoU 0.954 "
                        "at the ground-truth pose",
            },
            "cameras_preserved": [
                "front_camera", "side_camera", "v22_left_d405_rgb",
                "v22_right_d405_rgb", "chest_d435i_preview"],
            "render_check": {
                "lit_pixel_fraction": lit_frac,
                "note": "a camera aimed the wrong way renders black without "
                        "raising anything, so the build renders one frame and "
                        "refuses to write a config if it is essentially black",
            },
        },
        "grasp": {
            "arm": "right",
            "arm_joints": 7,
            "finger_joint_range_m": [0.0, 0.044],
            "planner": "handeye_grasp_red_cube.search_reachable_grasp",
            "axis_policy": (
                "MUST BE PINNED. search_reachable_grasp() picks whichever of the "
                "six signed world axes has the lowest IK residual, and that winner "
                "flips between calls (measured: y- at 18.1 mm residual, then y+ at "
                "9.8 mm after the target moved). Different signed axes are mirror "
                "images, so anything that corrects the grasp across calls must hold "
                "the axis fixed. This also explains run-to-run differences of the "
                "same plan (2 contacts in one run, 0 in another)."),
            "calibrated_axis": "y-",
            "calibrated_offset_mm": [-48.0, 5.3, 25.2],
            "calibration_method": (
                "Close once, read the contact centroid in the object frame, shift "
                "the requested grasp centre by minus that, repeat. Converged in 5 "
                "passes from 37.0 mm off centre to 4.2 mm off centre."),
            "measured_grip_force_n": 6.085,
            "measured_grip_force_per_finger_n": 3.043,
            "friction_requirement_n_per_finger": float(CUBE_MASS * 9.81 / 2.0),
            "requirement_derivation": "2*mu*N >= m*g, mu=1.0, m=0.18 kg -> N >= 0.883 N",
            "margin": 3.4,
            "weld": "not used anywhere",
            "contact_model": {
                "pair_count": 4,
                "condim": 4,
                "sliding_friction": 1.0,
                "torsional_friction_m": PAD_TORSIONAL_FRICTION,
                "solref": [0.005, 1.0],
                "reason": (
                    "The imported pad mesh yields one point on each opposing "
                    "cube face. condim=4 models the torsional resistance of a "
                    "finite pad contact patch; no weld is used."),
            },
            "known_limitation": (
                "The 5-pass recentring is a calibration procedure, not an execution "
                "path: 5 passes x ~8 s of sim far exceeds the task book's 15 s "
                "budget. For a fixed scene, calibrate once and bake the offset in; "
                "the episode itself is then a single pass."),
        },
        "validation_scope": (
            "MJCF compile of the frozen scene plus the wrapper camera, and the "
            "physics parameters read back out of the compiled model. The grasp "
            "numbers come from a closed-loop measurement in this scene. NOT "
            "verified here: perception accuracy on other object poses, the 15 s "
            "budget, or anything outside the right arm."),
    }
    CONFIG.write_text(json.dumps(config, indent=2, ensure_ascii=False, default=float) + "\n",
                      encoding="utf-8", newline="\n")
    print(f"wrote {WRAPPER}")
    print(f"wrote {CONFIG}")
    print(f"  frozen scene sha256 {src_sha}")
    print(f"  cube {2*CUBE_HALF*1000:.1f} mm box, {CUBE_MASS} kg, "
          f"mu={model.geom_friction[og][0]:.2f}, resting z {resting_z*1000:.1f} mm")
    print(f"  camera {CAM_NAME} at {np.round(pos,4)}, fovy {f} deg")
    return 0


def verify() -> int:
    if not CONFIG.is_file():
        print("no config to verify against; run the build first", file=sys.stderr)
        return 1
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    want = config["source_sha256"]
    got = sha256(FROZEN)
    if got != want:
        print("FROZEN SCENE CHANGED", file=sys.stderr)
        print(f"  expected {want}", file=sys.stderr)
        print(f"  actual   {got}", file=sys.stderr)
        print("droid_cube_scene.xml has been modified or regenerated. Every "
              "measurement recorded in the config was taken against the old file.",
              file=sys.stderr)
        return 1
    if not WRAPPER.is_file():
        print(f"FROZEN WRAPPER MISSING: {WRAPPER}", file=sys.stderr)
        return 1
    wrapper_want = config.get("output_sha256")
    if not wrapper_want:
        print("config has no output_sha256; rebuild once to protect the wrapper",
              file=sys.stderr)
        return 1
    wrapper_got = sha256(WRAPPER)
    if wrapper_got != wrapper_want:
        print("FROZEN WRAPPER CHANGED", file=sys.stderr)
        print(f"  expected {wrapper_want}", file=sys.stderr)
        print(f"  actual   {wrapper_got}", file=sys.stderr)
        print("droid_cube_scene_perception.xml was overwritten. Rebuild it from "
              "build_droid_cube_perception_scene.py before using the scene.",
              file=sys.stderr)
        return 1
    print(f"frozen source unchanged  ({got})")
    print(f"frozen wrapper unchanged ({wrapper_got})")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--verify", action="store_true",
                    help="only re-check that the frozen scene still matches its recorded hash")
    sys.exit(verify() if ap.parse_args().verify else build())
